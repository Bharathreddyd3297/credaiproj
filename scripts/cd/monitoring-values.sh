#!/usr/bin/env bash
# =====================================================================
# Generate the environment-specific values for kube-prometheus-stack:
# Grafana's public host and certificate issuer, and the Alertmanager
# receivers. The file holds NO secrets: Alertmanager reads the Slack
# webhook URL from the mounted Secret "alertmanager-slack" (api_url_file).
#
#   scripts/cd/monitoring-values.sh <out file>
#
# Environment variables:
#   DOMAIN          e.g. 20-48-1-2.sslip.io -> Grafana at grafana.<DOMAIN>
#   TLS_ISSUER      letsencrypt-prod | letsencrypt-staging | selfsigned
#   SLACK_ENABLED   true = CREDPAY alerts to Slack (Secret alertmanager-slack
#                   must exist); otherwise alerts stay in Alertmanager
# =====================================================================
set -euo pipefail
out="${1:?usage: monitoring-values.sh <out file>}"
grafana_host="grafana.${DOMAIN:?DOMAIN is required}"
issuer="${TLS_ISSUER:-letsencrypt-prod}"

cat > "$out" <<YAML
# Generated by scripts/cd/monitoring-values.sh - do not edit by hand
grafana:
  ingress:
    annotations:
      cert-manager.io/cluster-issuer: $issuer
    hosts: [$grafana_host]
    tls:
      - secretName: grafana-tls
        hosts: [$grafana_host]
  grafana.ini:
    server:
      root_url: https://$grafana_host
YAML

if [ "${SLACK_ENABLED:-false}" = true ]; then
  cat >> "$out" <<YAML
alertmanager:
  alertmanagerSpec:
    # Mounted at /etc/alertmanager/secrets/alertmanager-slack/<key>
    secrets: [alertmanager-slack]
  config:
    route:
      receiver: "null"
      group_by: [alertname, namespace, service]
      group_wait: 30s
      group_interval: 5m
      repeat_interval: 4h
      routes:
        - receiver: "null"
          matchers: ['alertname = "Watchdog"']
        # Every CREDPAY alert (and its resolution) is posted to Slack
        - receiver: slack
          matchers: ['team = "credpay"']
    receivers:
      - name: "null"
      - name: slack
        slack_configs:
          - api_url_file: /etc/alertmanager/secrets/alertmanager-slack/webhook_url
            send_resolved: true
            title_link: https://$grafana_host/d/credpay-overview
YAML
  # Alertmanager message templates (quoted heredoc: no shell expansion)
  cat >> "$out" <<'YAML'
            color: '{{ if eq .Status "firing" }}{{ if eq .CommonLabels.severity "critical" }}danger{{ else }}warning{{ end }}{{ else }}good{{ end }}'
            title: '{{ if eq .Status "firing" }}:rotating_light: FIRING{{ else }}:white_check_mark: RESOLVED{{ end }}: {{ .CommonLabels.alertname }} ({{ .CommonLabels.namespace }})'
            text: |-
              {{ range .Alerts }}*{{ .Labels.severity | toUpper }}* {{ .Annotations.summary }}
              {{ .Annotations.description }}
              {{ if .Annotations.runbook_url }}<{{ .Annotations.runbook_url }}|Runbook>{{ end }}
              {{ end }}
YAML
  echo "Alertmanager: CREDPAY alerts -> Slack"
else
  echo "Alertmanager: Slack not configured - alerts are visible in Alertmanager, Grafana and the admin portal only"
fi
echo "Grafana: https://$grafana_host"
