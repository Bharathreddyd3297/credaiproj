import { useCallback, useEffect, useState } from 'react';
import {
  Alert,
  Box,
  Button,
  Chip,
  CircularProgress,
  LinearProgress,
  Link,
  Paper,
  Stack,
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableRow,
  Typography,
} from '@mui/material';
import appConfig from '../config';
import { extractErrorMessage, fetchAiInsight, fetchAiOverview } from '../services/api';
import { formatDateTime } from '../lib/format';
import { glassCard } from '../theme/theme';

const REFRESH_MS = 30000;
const STATUS = {
  healthy: { color: 'success', label: 'Healthy' },
  degraded: { color: 'warning', label: 'Degraded' },
  down: { color: 'error', label: 'Down' },
};
const SEVERITY_COLOR = { critical: 'error', warning: 'warning' };

const percent = (v) => (v === null || v === undefined ? '-' : `${(v * 100).toFixed(1)}%`);
const seconds = (v) => (v === null || v === undefined ? '-' : `${(v * 1000).toFixed(0)} ms`);
const perSecond = (v) => (v === null || v === undefined ? '-' : v.toFixed(2));

/**
 * Live health of this environment from the AIOps service (ai-service):
 * Prometheus metrics, Kubernetes, firing alerts, Dynatrace problems, and
 * an on-demand briefing (Azure OpenAI or rule-based).
 */
export default function MonitoringPage() {
  if (!appConfig.aiopsEnabled) {
    return <NotEnabled />;
  }
  return <LiveMonitoring />;
}

function LiveMonitoring() {
  const [overview, setOverview] = useState(null);
  const [error, setError] = useState('');
  const [insight, setInsight] = useState(null);
  const [insightError, setInsightError] = useState('');
  const [thinking, setThinking] = useState(false);

  const refresh = useCallback(() => {
    fetchAiOverview()
      .then((data) => {
        setOverview(data);
        setError('');
      })
      .catch((err) => setError(extractErrorMessage(err, 'Could not load the monitoring overview.')));
  }, []);

  useEffect(() => {
    refresh();
    const timer = setInterval(refresh, REFRESH_MS);
    return () => clearInterval(timer);
  }, [refresh]);

  const generateBriefing = async () => {
    setThinking(true);
    setInsightError('');
    try {
      const data = await fetchAiInsight();
      setInsight(data);
      setOverview(data.overview);
    } catch (err) {
      setInsightError(extractErrorMessage(err, 'Could not generate the briefing.'));
    } finally {
      setThinking(false);
    }
  };

  if (error && !overview) return <Alert severity="error">{error}</Alert>;
  if (!overview) return <CircularProgress />;

  const status = STATUS[overview.status] || STATUS.degraded;

  return (
    <Box sx={{ animation: 'fadeInUp .4s ease both' }}>
      <Stack direction="row" spacing={1.5} alignItems="center" sx={{ mb: 0.5, flexWrap: 'wrap' }}>
        <Typography variant="h3">Monitoring</Typography>
        <Chip label={status.label} color={status.color} />
        <Chip label={overview.environment} variant="outlined" size="small" />
      </Stack>
      <Typography color="text.secondary" sx={{ mb: 3 }}>
        Updated {formatDateTime(overview.generatedAt)} · refreshes every 30 seconds
      </Typography>

      {error && (
        <Alert severity="warning" sx={{ mb: 2 }}>
          {error} Showing the last successful update.
        </Alert>
      )}

      <ExternalLinks />

      {/* ---- AI briefing ------------------------------------------------ */}
      <Paper elevation={0} sx={{ ...glassCard, p: 3, mb: 3 }}>
        <Stack direction={{ xs: 'column', sm: 'row' }} spacing={2} alignItems={{ sm: 'center' }} sx={{ mb: 2 }}>
          <Box sx={{ flexGrow: 1 }}>
            <Typography variant="h6">AIOps briefing</Typography>
            <Typography variant="body2" color="text.secondary">
              {overview.sources.azure_openai === 'ok'
                ? 'Written by Azure OpenAI from the facts on this page.'
                : 'Rule-based summary (add the Azure OpenAI settings for an AI-written briefing).'}
            </Typography>
          </Box>
          <Button variant="contained" onClick={generateBriefing} disabled={thinking}>
            {thinking ? 'Analysing…' : 'Generate briefing'}
          </Button>
        </Stack>
        {thinking && <LinearProgress sx={{ mb: 2 }} />}
        {insightError && <Alert severity="error">{insightError}</Alert>}
        {insight && (
          <>
            <Typography component="pre" sx={{ whiteSpace: 'pre-wrap', fontFamily: 'inherit', m: 0 }}>
              {insight.summary}
            </Typography>
            <Typography variant="caption" color="text.secondary">
              Generated by {insight.generatedBy === 'azure-openai' ? 'Azure OpenAI' : 'rules'}
            </Typography>
          </>
        )}
      </Paper>

      <Box sx={{ display: 'grid', gap: 3, gridTemplateColumns: { xs: '1fr', lg: '1.4fr 1fr' } }}>
        {/* ---- Services ------------------------------------------------- */}
        <Paper elevation={0} sx={{ ...glassCard, p: 3 }}>
          <Typography variant="h6" sx={{ mb: 2 }}>
            Services
          </Typography>
          <Table size="small">
            <TableHead>
              <TableRow>
                <TableCell>Service</TableCell>
                <TableCell>State</TableCell>
                <TableCell align="right">Pods</TableCell>
                <TableCell align="right">Req/s</TableCell>
                <TableCell align="right">Errors</TableCell>
                <TableCell align="right">p95</TableCell>
              </TableRow>
            </TableHead>
            <TableBody>
              {overview.services.map((s) => (
                <TableRow key={s.name}>
                  <TableCell>{s.name}</TableCell>
                  <TableCell>
                    {s.up === null ? (
                      <Chip label="no metrics" size="small" variant="outlined" />
                    ) : (
                      <Chip label={s.up ? 'UP' : 'DOWN'} size="small" color={s.up ? 'success' : 'error'} variant="outlined" />
                    )}
                  </TableCell>
                  <TableCell align="right">
                    {s.replicas ? `${s.replicas.available}/${s.replicas.desired}` : '-'}
                  </TableCell>
                  <TableCell align="right">{perSecond(s.requestsPerSecond)}</TableCell>
                  <TableCell align="right">{percent(s.errorRatio)}</TableCell>
                  <TableCell align="right">{seconds(s.latencyP95Seconds)}</TableCell>
                </TableRow>
              ))}
            </TableBody>
          </Table>
          {overview.restartingPods.length > 0 && (
            <Typography variant="body2" color="warning.main" sx={{ mt: 2 }}>
              Restarted in the last hour: {overview.restartingPods.map((p) => p.pod).join(', ')}
            </Typography>
          )}
        </Paper>

        {/* ---- Alerts and problems ----------------------------------------- */}
        <Stack spacing={3}>
          <Paper elevation={0} sx={{ ...glassCard, p: 3 }}>
            <Typography variant="h6" sx={{ mb: 2 }}>
              Firing alerts ({overview.alerts.length})
            </Typography>
            {overview.alerts.length === 0 ? (
              <Typography color="text.secondary">No alerts firing.</Typography>
            ) : (
              <Stack spacing={1.5}>
                {overview.alerts.map((a, i) => (
                  <Box key={`${a.name}-${i}`}>
                    <Stack direction="row" spacing={1} alignItems="center">
                      <Chip label={a.severity} size="small" color={SEVERITY_COLOR[a.severity] || 'default'} />
                      <Typography fontWeight={600}>{a.name}</Typography>
                    </Stack>
                    <Typography variant="body2" color="text.secondary">
                      {a.summary}
                      {a.runbook && (
                        <>
                          {' · '}
                          <Link href={a.runbook} target="_blank" rel="noopener">
                            runbook
                          </Link>
                        </>
                      )}
                    </Typography>
                  </Box>
                ))}
              </Stack>
            )}
          </Paper>

          <Paper elevation={0} sx={{ ...glassCard, p: 3 }}>
            <Typography variant="h6" sx={{ mb: 2 }}>
              Dynatrace problems
            </Typography>
            {overview.sources.dynatrace === 'not_configured' ? (
              <Typography color="text.secondary">Dynatrace is not connected for this environment.</Typography>
            ) : overview.problems.length === 0 ? (
              <Typography color="text.secondary">No open problems.</Typography>
            ) : (
              <Stack spacing={1.5}>
                {overview.problems.map((p) => (
                  <Box key={p.id}>
                    <Link href={p.link} target="_blank" rel="noopener" fontWeight={600}>
                      {p.id} · {p.title}
                    </Link>
                    <Typography variant="body2" color="text.secondary">
                      {p.severity} · {p.impact}
                      {p.rootCause ? ` · root cause: ${p.rootCause}` : ''}
                    </Typography>
                  </Box>
                ))}
              </Stack>
            )}
          </Paper>
        </Stack>
      </Box>

      <Stack direction="row" spacing={1} sx={{ mt: 3, flexWrap: 'wrap' }}>
        {Object.entries(overview.sources).map(([name, state]) => (
          <Chip
            key={name}
            size="small"
            variant="outlined"
            label={`${name}: ${state.replace('_', ' ')}`}
            color={state === 'ok' ? 'success' : state === 'unavailable' ? 'error' : 'default'}
          />
        ))}
      </Stack>
    </Box>
  );
}

function ExternalLinks() {
  const links = [
    ['Grafana dashboards', appConfig.grafanaUrl],
    ['Dynatrace', appConfig.dynatraceUrl],
  ].filter(([, url]) => url);
  if (links.length === 0) return null;
  return (
    <Stack direction="row" spacing={1.5} sx={{ mb: 3, flexWrap: 'wrap' }}>
      {links.map(([label, url]) => (
        <Button key={label} variant="outlined" size="small" href={url} target="_blank" rel="noopener">
          {label}
        </Button>
      ))}
    </Stack>
  );
}

function NotEnabled() {
  return (
    <Box sx={{ animation: 'fadeInUp .4s ease both' }}>
      <Typography variant="h3" sx={{ mb: 0.5 }}>
        Monitoring
      </Typography>
      <Typography color="text.secondary" sx={{ mb: 3, maxWidth: 720 }}>
        Monitoring and AIOps are switched on in the prod environment (Prometheus, Grafana, alerting,
        Dynatrace and the AIOps briefing). This environment does not run them.
      </Typography>
      <ExternalLinks />
    </Box>
  );
}
